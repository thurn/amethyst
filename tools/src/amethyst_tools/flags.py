"""Flags from the C# declarations (FLAGS.md): list them, regenerate FLAGS.md's tables, check
declarations, presets and variants, and find flags nothing reads.

A declaration is one statement, which this scanner reads with a regular expression:

    public static readonly Flag<SwordArc> Arc = Flag.Enum("sword.arc", SwordArc.Wide, "...");
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path

from . import paths

DECL: re.Pattern[str] = re.compile(
    r"static\s+readonly\s+Flag<[^>]+>\s+(?P<field>\w+)\s*=\s*"
    r"Flag\.(?P<kind>Bool|Int|Float|String|Enum)\s*(?:<[^>]*>)?\s*\(\s*"
    r'"(?P<name>[^"]+)"\s*,\s*(?P<default>"(?:[^"\\]|\\.)*"|[^,()]+?)\s*,\s*'
    r'"(?P<about>(?:[^"\\]|\\.)*)"\s*\)\s*;',
)
CALL: re.Pattern[str] = re.compile(
    r"\bFlag\.(?:Bool|Int|Float|String|Enum)\s*(?:<[^>]*>)?\s*\("
)
CLASS: re.Pattern[str] = re.compile(r"\b(?:class|struct)\s+(\w+)")
ENUM: re.Pattern[str] = re.compile(r"\benum\s+(\w+)\s*\{([^}]*)\}")
NAME: re.Pattern[str] = re.compile(r"^[a-z][a-z0-9-]*(\.[a-z][a-z0-9-]*)+$")
MARKER = "<!-- Generated by `just flags-doc` from the declarations; edit those. -->"


@dataclass(frozen=True)
class FlagDecl:
    name: str
    kind: str
    default: str
    about: str
    owner: str  # packages/<package>, game or testbeds/<name>
    path: str
    line: int
    cls: str
    field: str
    choices: tuple[str, ...]

    @property
    def type_text(self) -> str:
        return " | ".join(self.choices) if self.choices else self.kind.lower()


def kebab(pascal: str) -> str:
    """`WideArc` to `wide-arc`, as FlagText.Kebab does."""
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"-\1", pascal).lower()


def tracked(pattern: str) -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-co", "--exclude-standard", "--", pattern],
        cwd=paths.REPO,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return [p for p in out.splitlines() if "/Assets/Vendor/" not in p]


def code_files() -> list[str]:
    """The game's C#: not the dotnet harness or tests, whose flags are fixtures."""
    return [
        p for p in tracked("*.cs") if not p.startswith("dotnet/") and "/Tests/" not in p
    ]


def owner_of(path: str) -> str:
    parts = path.split("/")
    if parts[0] in ("packages", "testbeds") and len(parts) > 2:
        return "/".join(parts[:2])
    return parts[0]


def enums(sources: dict[str, str]) -> dict[str, tuple[str, ...]]:
    found: dict[str, tuple[str, ...]] = {}
    for text in sources.values():
        for m in ENUM.finditer(text):
            members = re.sub(r"//.*|/\*.*?\*/|\[[^\]]*\]", "", m.group(2), flags=re.S)
            names = [n.split("=")[0].strip() for n in members.split(",")]
            found[m.group(1)] = tuple(kebab(n) for n in names if n)
    return found


def scan() -> tuple[list[FlagDecl], list[str]]:
    """Every declaration, and the problems: unparsable or duplicate declarations, bad names."""
    sources = {p: (paths.REPO / p).read_text(encoding="utf-8") for p in code_files()}
    known = enums(sources)
    decls: list[FlagDecl] = []
    errors: list[str] = []
    for path, text in sources.items():
        parsed = 0
        for m in DECL.finditer(text):
            parsed += 1
            line = text.count("\n", 0, m.start()) + 1
            classes = CLASS.findall(text, 0, m.start())
            default = m.group("default").strip()
            choices: tuple[str, ...] = ()
            if m.group("kind") == "Enum":
                enum_type, _, member = default.rpartition(".")
                choices = known.get(enum_type.split(".")[-1], ())
                default = kebab(member)
            elif default.startswith('"'):
                default = default[1:-1]
            else:
                default = (
                    default.rstrip("fFdDmM") if m.group("kind") == "Float" else default
                )
            decls.append(
                FlagDecl(
                    m.group("name"),
                    m.group("kind"),
                    default,
                    m.group("about").replace('\\"', '"'),
                    owner_of(path),
                    path,
                    line,
                    classes[-1] if classes else "?",
                    m.group("field"),
                    choices,
                )
            )
        calls = len(CALL.findall(text))
        if calls > parsed and not path.endswith("Flags/Flag.cs"):
            errors.append(
                f"{path}: {calls - parsed} flag declaration(s) not in the form "
                f'`static readonly Flag<T> F = Flag.Kind("name", default, "about");`'
            )
    seen: dict[str, FlagDecl] = {}
    for d in decls:
        if not NAME.match(d.name):
            errors.append(
                f"{d.path}:{d.line}: {d.name!r} needs a dotted lowercase name"
            )
        if d.name in seen:
            errors.append(
                f"{d.path}:{d.line}: {d.name} is also declared in {seen[d.name].path}"
            )
        seen[d.name] = d
    return sorted(decls, key=lambda d: d.name), errors


def valid(decl: FlagDecl, value: str) -> bool:
    v = value.strip()
    if decl.kind == "Bool":
        return v.lower() in ("true", "false", "on", "off", "yes", "no", "1", "0")
    if decl.kind == "Int":
        return re.fullmatch(r"[+-]?\d+", v) is not None
    if decl.kind == "Float":
        try:
            float(v)
            return v.lower() not in ("nan", "inf", "-inf", "infinity")
        except ValueError:
            return False
    if decl.kind == "Enum":
        squash = v.replace("-", "").lower()
        return any(c.replace("-", "") == squash for c in decl.choices)
    return True


def read_flag_file(path: Path) -> tuple[str, list[tuple[int, str, str]], list[str]]:
    """(about, [(line, name, value)], errors) of a .flags file, as FlagFile.Parse reads it."""
    about: list[str] = []
    values: list[tuple[int, str, str]] = []
    errors: list[str] = []
    for i, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = raw.strip()
        if not line:
            continue
        if line.startswith("#"):
            if not values:
                about.append(line.lstrip("#").strip())
            continue
        name, eq, value = line.partition("=")
        if not eq or not name.strip():
            errors.append(f"line {i}: expected 'name = value'")
            continue
        values.append((i, name.strip(), value.strip()))
    return " ".join(about), values, errors


def scope(owner: str) -> set[str]:
    """The owners whose flags a project's presets and variants may set: itself and the
    packages its manifest uses."""
    manifest = paths.REPO / owner / "Packages" / "manifest.json"
    owners = {owner}
    if manifest.exists():
        deps = json.loads(manifest.read_text()).get("dependencies", {})
        owners |= {
            f"packages/{n}" for n, spec in deps.items() if str(spec).startswith("file:")
        }
    return owners


def check_flag_files(decls: list[FlagDecl]) -> list[str]:
    by_name = {d.name: d for d in decls}
    errors = []
    for rel in tracked("*.flags"):
        allowed = scope(owner_of(rel))
        _, values, problems = read_flag_file(paths.REPO / rel)
        errors += [f"{rel}: {p}" for p in problems]
        for line, name, value in values:
            d = by_name.get(name)
            if d is None or d.owner not in allowed:
                errors.append(
                    f"{rel}:{line}: unknown flag {name!r} for {owner_of(rel)}"
                )
            elif not valid(d, value):
                errors.append(
                    f"{rel}:{line}: {value!r} is not a {d.type_text} for {name}"
                )
    return errors


def mdformat(text: str) -> str:
    run = subprocess.run(
        [sys.executable, "-m", "mdformat", "--wrap", "80", "--number", "-"],
        cwd=paths.REPO,
        input=text,
        capture_output=True,
        text=True,
        check=True,
    )
    return run.stdout


def generated(decls: list[FlagDecl]) -> str:
    groups: dict[str, list[FlagDecl]] = defaultdict(list)
    for d in decls:
        groups[d.owner].append(d)
    files: dict[str, list[str]] = defaultdict(list)
    for rel in sorted(tracked("*.flags")):
        files[owner_of(rel)].append(rel)
    owners = set(groups) | set(files)
    order = sorted(
        owners, key=lambda o: (not o.startswith("packages/"), o != "game", o)
    )
    out = [MARKER, ""]
    for owner in order:
        out += [f"### {owner}", ""]
        for d in groups[owner]:
            values = (
                f"{d.kind.lower()}: {' | '.join(d.choices)}"
                if d.choices
                else d.kind.lower()
            )
            where = f"[{Path(d.path).name}:{d.line}]({d.path}#L{d.line})"
            out.append(f"- `{d.name}` = `{d.default}` ({values}): {d.about}. {where}")
        if groups[owner] and files[owner]:
            out.append("")
        for rel in files[owner]:
            about, values, _ = read_flag_file(paths.REPO / rel)
            kind = Path(rel).parent.name.rstrip("s")
            sets = ", ".join(f"`{n}={v}`" for _, n, v in values)
            link = f"[{Path(rel).name}]({rel})"
            out.append(f"- {kind} `{Path(rel).stem}`: {about}. Sets {sets}. {link}")
        out.append("")
    return "\n".join(out)


def document(decls: list[FlagDecl]) -> str:
    current = (paths.REPO / "FLAGS.md").read_text(encoding="utf-8")
    head = current.split(MARKER)[0].rstrip() + "\n\n"
    return mdformat(head + generated(decls))


# Commands.


def list_flags(args: argparse.Namespace) -> int:
    decls, errors = scan()
    for d in decls:
        text = f"{d.name} {d.owner} {d.about}"
        if args.filter and args.filter not in text:
            continue
        print(
            f"{d.name:28} {d.type_text:32} {d.default:10} {d.about}  ({d.path}:{d.line})"
        )
    for e in errors:
        print(f"error: {e}", file=sys.stderr)
    return 1 if errors else 0


def doc(args: argparse.Namespace) -> int:
    decls, errors = scan()
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    (paths.REPO / "FLAGS.md").write_text(document(decls), encoding="utf-8")
    print(f"FLAGS.md: {len(decls)} flags")
    return 0


def check(args: argparse.Namespace) -> int:
    decls, errors = scan()
    errors += check_flag_files(decls)
    if not errors and (paths.REPO / "FLAGS.md").read_text(encoding="utf-8") != document(
        decls
    ):
        errors.append("FLAGS.md is stale: run `just flags-doc`")
    for e in errors:
        print(f"flags: {e}")
    return 1 if errors else 0


def unused(args: argparse.Namespace) -> int:
    decls, _ = scan()
    sources = {p: (paths.REPO / p).read_text(encoding="utf-8") for p in code_files()}
    idle = []
    for d in decls:
        qualified = re.compile(rf"\b{d.cls}\.{d.field}\b")
        bare = re.compile(rf"\b{d.field}\b")
        uses = sum(len(qualified.findall(t)) for t in sources.values())
        uses += (
            len(bare.findall(sources[d.path])) - 1
        )  # its own class, past the declaration
        if uses <= 0:
            idle.append(d)
    for d in idle:
        print(f"{d.name:28} {d.path}:{d.line}")
    print(
        f"{len(idle)} of {len(decls)} flags are never read: delete them, or their losing branches"
    )
    return 0


def register(sub: argparse._SubParsersAction[argparse.ArgumentParser]) -> None:
    p = sub.add_parser("flags", help="list, document and check flags")
    actions = p.add_subparsers(dest="action", required=True)
    a = actions.add_parser("list", help="every flag")
    a.add_argument("filter", nargs="?")
    a.set_defaults(func=list_flags)
    actions.add_parser("doc", help="regenerate FLAGS.md's tables").set_defaults(
        func=doc
    )
    actions.add_parser(
        "check", help="declarations, presets, variants, FLAGS.md"
    ).set_defaults(func=check)
    actions.add_parser("unused", help="flags nothing reads").set_defaults(func=unused)
